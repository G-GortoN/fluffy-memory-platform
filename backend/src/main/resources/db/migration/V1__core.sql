CREATE TABLE accounts (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       text NOT NULL UNIQUE,
    name        text NOT NULL,
    password_hash text NOT NULL,
    role        text NOT NULL CHECK (role IN ('CUSTOMER', 'ADMIN')),
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE media (
    id          uuid PRIMARY KEY,
    owner_id    bigint NOT NULL REFERENCES accounts(id),
    content_type text NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png')),
    size_bytes  bigint NOT NULL CHECK (size_bytes > 0),
    operations_access boolean NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE admin_actions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id bigint NOT NULL REFERENCES accounts(id),
    action      text NOT NULL,
    subject_type text NOT NULL,
    subject_id  bigint NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE pets (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    bigint NOT NULL REFERENCES accounts(id),
    name        text NOT NULL,
    species     text NOT NULL CHECK (species IN ('CAT', 'DOG')),
    breed       text,
    age_months  integer NOT NULL CHECK (age_months BETWEEN 0 AND 600),
    weight_kg   numeric(7, 2) CHECK (weight_kg > 0),
    status      text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DECEASED')),
    photo_id    uuid REFERENCES media(id),
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX pets_by_owner ON pets(owner_id, id);

CREATE TABLE memorials (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    bigint NOT NULL REFERENCES accounts(id),
    pet_id      bigint UNIQUE REFERENCES pets(id) ON DELETE SET NULL,
    pet_name    text NOT NULL,
    title       text NOT NULL,
    story       text NOT NULL DEFAULT '',
    photo_id    uuid REFERENCES media(id),
    template    text NOT NULL CHECK (template IN ('CORNER', 'HALL')),
    share_hash  text UNIQUE,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX memorials_by_owner ON memorials(owner_id, id);

CREATE TABLE memorial_gallery (
    memorial_id bigint NOT NULL REFERENCES memorials(id) ON DELETE CASCADE,
    position    integer NOT NULL CHECK (position BETWEEN 0 AND 19),
    photo_id    uuid NOT NULL REFERENCES media(id),
    PRIMARY KEY (memorial_id, position)
);

CREATE TABLE memorial_timeline (
    memorial_id bigint NOT NULL REFERENCES memorials(id) ON DELETE CASCADE,
    position    integer NOT NULL CHECK (position BETWEEN 0 AND 19),
    moment_date date NOT NULL,
    details     text NOT NULL,
    PRIMARY KEY (memorial_id, position)
);

CREATE TABLE care_cards (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       text NOT NULL,
    summary     text NOT NULL,
    body        text NOT NULL,
    source_url  text NOT NULL,
    product_id  bigint,
    species     text NOT NULL CHECK (species IN ('ALL', 'CAT', 'DOG')),
    stage       text NOT NULL CHECK (stage IN ('ALL', 'YOUNG', 'ADULT', 'SENIOR')),
    breed       text,
    published   boolean NOT NULL DEFAULT false,
    updated_at  timestamptz NOT NULL DEFAULT now()
);


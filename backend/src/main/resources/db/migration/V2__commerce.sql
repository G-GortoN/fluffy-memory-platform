create table products (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    description varchar(3000) not null,
    category varchar(20) not null check (category in ('FOOD', 'WELLNESS', 'BOWLS', 'FRAMES', 'KEEPSAKES', 'URNS')),
    image_url varchar(500) not null,
    custom boolean not null,
    active boolean not null
);

create table product_variants (
    id bigint generated by default as identity primary key,
    product_id bigint not null references products(id),
    name varchar(80) not null,
    price_cents integer not null check (price_cents > 0),
    stock integer not null check (stock >= 0),
    active boolean not null default true
);
create index product_variants_product on product_variants(product_id);

create table cart_items (
    id bigint generated by default as identity primary key,
    account_id bigint not null references accounts(id) on delete cascade,
    variant_id bigint not null references product_variants(id),
    quantity integer not null check (quantity between 1 and 99),
    custom_text varchar(120),
    custom_photo_url varchar(200)
);
create index cart_items_account on cart_items(account_id, id);

create table orders (
    id bigint generated by default as identity primary key,
    account_id bigint not null references accounts(id),
    request_id varchar(100) not null,
    status varchar(24) not null check (status in ('PENDING_PAYMENT', 'PAID', 'PARTIALLY_SHIPPED', 'SHIPPED', 'COMPLETED', 'CANCELLED', 'REFUND_REQUESTED', 'REFUNDED')),
    subtotal_cents bigint not null check (subtotal_cents > 0),
    shipping_cents integer not null check (shipping_cents >= 0),
    recipient varchar(60) not null,
    phone varchar(32) not null,
    address varchar(300) not null,
    created_at timestamptz not null default clock_timestamp(),
    expires_at timestamptz not null,
    paid_at timestamptz,
    refunded_at timestamptz,
    refund_reason varchar(500),
    refund_from_status varchar(24),
    unique (account_id, request_id)
);
create index orders_account on orders(account_id, id desc);
create index orders_expiry on orders(expires_at) where status = 'PENDING_PAYMENT';

create table shipments (
    id bigint generated by default as identity primary key,
    order_id bigint not null references orders(id),
    carrier varchar(60) not null,
    tracking_no varchar(80) not null,
    shipped_at timestamptz not null default clock_timestamp(),
    unique (order_id, id),
    unique (order_id, carrier, tracking_no)
);

create table order_items (
    id bigint generated by default as identity primary key,
    order_id bigint not null references orders(id),
    product_id bigint not null references products(id),
    variant_id bigint not null references product_variants(id),
    product_name varchar(100) not null,
    variant_name varchar(80) not null,
    price_cents integer not null check (price_cents > 0),
    quantity integer not null check (quantity between 1 and 99),
    custom_text varchar(120),
    custom_photo_url varchar(200),
    production_status varchar(20) not null check (production_status in ('NOT_REQUIRED', 'AWAITING_PAYMENT', 'QUEUED', 'IN_PRODUCTION', 'READY', 'CANCELLED')),
    shipment_id bigint,
    foreign key (order_id, shipment_id) references shipments(order_id, id)
);
create index order_items_order on order_items(order_id, id);

